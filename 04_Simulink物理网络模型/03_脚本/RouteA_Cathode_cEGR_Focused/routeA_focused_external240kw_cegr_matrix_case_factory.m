function [totalFlowStudy, totalFlowMatrix, freshAirStudy, freshAirMatrix] = ...
    routeA_focused_external240kw_cegr_matrix_case_factory(overrides)
% Build the two formal 240-kW V-SH passive-cEGR screening batches.
%
% Run the returned studies separately with run_routeA_focused_study:
%   totalResult = run_routeA_focused_study(totalFlowStudy);
%   freshResult = run_routeA_focused_study(freshAirStudy);
%
% These studies are bound to the current V-SH topology:
%   stack cathode outlet -> ideal split -> V_EGR -> compressor inlet
%                                     -> V_BP  -> ambient exhaust.
% The v02 result filenames are deliberately retained so a completed rerun
% replaces the invalid valve-after-split matrix results in place. Do not
% merge old and new MAT rows.
%
% The canonical study coordinate is R_EGR=m_return/m_fresh at the
% compressor inlet. The existing valve controller accepts x_EGR=m_return/
% m_total, so every case applies x_EGR=R_EGR/(1+R_EGR) explicitly.
% Batch A keeps total compressor-inlet flow at the reference OER for each
% load. Batch B keeps that reference fresh-air flow and uses mode 4 to
% increase total compressor flow as cEGR increases.

if nargin < 1 || isempty(overrides)
    overrides = struct();
end
settings = defaultSettings(overrides);
conditions = recommendedConditions();

[totalCases, totalRows] = buildCases(conditions, settings, "total_flow_fixed");
[freshCases, freshRows] = buildCases(conditions, settings, "fresh_air_fixed");
contract = screenContract();

totalFlowStudy = studyConfig(totalCases, settings, contract, "total_flow_fixed");
freshAirStudy = studyConfig(freshCases, settings, contract, "fresh_air_fixed");
totalFlowMatrix = matrixDescriptor(totalRows, conditions, settings, contract, ...
    "total_flow_fixed");
freshAirMatrix = matrixDescriptor(freshRows, conditions, settings, contract, ...
    "fresh_air_fixed");
end

function [cases, rows] = buildCases(conditions, settings, strategy)
switch strategy
    case "total_flow_fixed"
        ratioCount = numel(settings.totalFlowFractions);
    case "fresh_air_fixed"
        ratioCount = numel(settings.freshAirRecirculationR);
    otherwise
        error('RouteA:External240kWCEGRStrategy', 'Unknown flow strategy.');
end
caseCount = numel(conditions) * ratioCount;
cases = struct([]);
rows = repmat(rowTemplate(), caseCount, 1);
caseIndex = 0;
for conditionIndex = 1:numel(conditions)
    condition = conditions(conditionIndex);
    if strategy == "total_flow_fixed"
        recirculationR = (condition.referenceOER - 1) * ...
            settings.totalFlowFractions;
    else
        recirculationR = settings.freshAirRecirculationR;
    end
    for ratioIndex = 1:numel(recirculationR)
        R = recirculationR(ratioIndex);
        x = R / (1 + R);
        [caseCfg, ~] = routeA_focused_external240kw_case_factory( ...
            condition.currentDensity_A_cm2, struct( ...
            'cegrEnabled', R > 0, 'cegrTargetRatio', x));
        caseCfg = applyRecommendedCondition(caseCfg, condition);
        if strategy == "total_flow_fixed"
            caseCfg.air.modeId = 2;
            flowPolicy = "total_compressor_inlet_mdot_held_at_reference_OER";
        else
            caseCfg.air.modeId = 4;
            flowPolicy = "fresh_air_mdot_held_at_reference_OER_total_mdot_increases";
        end
        caseCfg.air.targetOer = condition.referenceOER;
        caseCfg.cegr.enabled = logical(R > 0);
        caseCfg.cegr.controlMode = 1;
        caseCfg.cegr.targetRatio = x;
        caseCfg.cegr.targetRecirculationR = R;
        caseCfg.cegr.profile = struct( ...
            'kind', "ramp", 'start_value', 0, 'end_value', x, ...
            'start_s', 0, 'end_s', settings.startupRampDuration_s);
        caseCfg.flowControlPolicy = flowPolicy;
        caseCfg.caseId = "external240_" + strategy + "_j" + ...
            numericLabel(condition.currentDensity_A_cm2, 1) + "_R" + ...
            numericLabel(R, 3);
        caseCfg.description = "External 240 kW V-SH passive cEGR; " + ...
            "strategy=" + strategy + ", R_EGR=m_return/m_fresh=" + ...
            string(R) + ", controller x_EGR=" + string(x) + ...
            ", reference OER=" + string(condition.referenceOER);
        caseIndex = caseIndex + 1;
        if caseIndex == 1
            cases = repmat(caseCfg, caseCount, 1);
        end
        cases(caseIndex) = caseCfg;
        rows(caseIndex) = buildRow(caseCfg, condition, R, x, strategy, ...
            flowPolicy);
    end
end
end

function caseCfg = applyRecommendedCondition(caseCfg, condition)
% Workbook cathode pressure is user-confirmed gauge pressure. The current
% V-SH stack-outlet pressure anchor receives ambient plus the workbook value;
% the ideal split then feeds V_EGR and V_BP. The gas temperature is the
% model's lumped compressor/intercooler boundary.
caseCfg.cathode.outletPressure_MPa_abs = ...
    condition.ambientPressure_MPa_abs + condition.cathodePressureGauge_kPa * 1e-3;
caseCfg.thermal.stackTemperatureSet_C = condition.stackTemperature_C;
caseCfg.focused.stackTemperature_C = condition.stackTemperature_C;
caseCfg.focused.cathodeGasTemperature_C = condition.cathodeGasTemperature_C;
caseCfg.recommendedTestCondition = condition;
end

function cfg = studyConfig(cases, settings, contract, strategy)
resultDir = fullfile(fileparts(mfilename('fullpath')), '..', '..', ...
    '02_结果', 'RouteA_Cathode_cEGR_Focused', 'outputs', ...
    '20260820_vsh_validation');
if isfield(settings, 'resultDir') && strlength(string(settings.resultDir)) > 0
    resultDir = char(settings.resultDir);
end
fileStem = "RouteA_Focused_External240kW_VSH_PassiveCEGR_" + strategy + ...
    "_4J_600s_20260820.mat";
if isfield(settings, 'resultTag') && strlength(string(settings.resultTag)) > 0
    fileStem = "RouteA_Focused_External240kW_VSH_PassiveCEGR_" + strategy + ...
        "_4J_600s_" + string(settings.resultTag) + ".mat";
end
cfg = struct( ...
    'modelId', "self_humidifying", ...
    'calculationType', "steady", ...
    'cases', cases, ...
    'researchDuration_s', settings.researchDuration_s, ...
    'tailLogicalWindow_s', settings.tailLogicalWindow_s, ...
    'steadyWindowDuration_s', settings.steadyWindowDuration_s, ...
    'retainSimulationOutputs', false, ...
    'executionMode', "parallel", ...
    'parallel', struct('poolProfile', settings.poolProfile, ...
        'workerCount', settings.workerCount, 'showProgress', true, ...
        'useFastRestart', false), ...
    'resultFile', string(fullfile(resultDir, fileStem)), ...
    'cegrScreenContract', contract);
end

function matrix = matrixDescriptor(rows, conditions, settings, contract, strategy)
matrix = struct( ...
    'schemaVersion', "RouteA_External240kW_VSH_CEGRMatrix_v03", ...
    'parameterLayer', "external_case", ...
    'purpose', "passive_cegr_pressure_temperature_oxygen_and_gas_phase_screen", ...
    'flowStrategy', strategy, ...
    'canonicalTargetDefinition', ...
        "R_EGR=m_return_over_m_fresh_at_compressor_inlet", ...
    'controllerTargetDefinition', ...
        "x_EGR=m_return_over_m_total=R_EGR_over_1_plus_R_EGR", ...
    'topology', contract.topology, ...
    'pressureReadbackContract', contract.pressureReadback, ...
    'resultReplacementPolicy', ...
        "overwrite_v02_only_after_each_complete_current_topology_batch;_do_not_merge_with_valve-after-split_rows", ...
    'actualOERObservable', ...
        "cathode_inlet_species_mdot_and_stack_current_tail_minimum", ...
    'recommendedConditions', conditions, ...
    'rows', rows, ...
    'auditTable', struct2table(rows), ...
    'caseCount', numel(rows), ...
    'totalFlowFractions', settings.totalFlowFractions, ...
    'freshAirRecirculationR', settings.freshAirRecirculationR, ...
    'source', "电堆信息及推荐测试工况.xlsx Sheet1", ...
    'cegrScreenContract', contract, ...
    'execution', struct('runner', "run_routeA_focused_study", ...
        'mode', "parallel", 'poolProfile', settings.poolProfile, ...
        'workerCount', settings.workerCount, 'coldStartOnly', true, ...
        'modelTime_s_per_case', settings.researchDuration_s, ...
        'tailWindow_s', settings.tailLogicalWindow_s));
end

