    'stackTemperature_C', {61.5, 64, 68, 80});
end

function contract = screenContract()
contract = struct( ...
    'schemaVersion', "RouteA_Focused_CEGRScreenContract_v03", ...
    'targetDefinition', ...
        "targetRecirculationR_and_actualRecirculationR_are_m_return_over_m_fresh_at_compressor_inlet;_controller_target_is_x_EGR=R_EGR_over_1_plus_R_EGR;_r_split_is_branch_only", ...
    'oer', struct('unacceptableBelow', 1, 'riskUpperInclusive', 1.2), ...
    'tracking', struct('absoluteTolerance', .005, ...
        'relativeTolerance', .05), ...
    'condensation', struct('nearSaturationRatio', .95, ...
        'nearDewMargin_C', 2, 'nonzeroRate_kg_s', 1e-10), ...
    'topology', struct( ...
        'id', "VSH_StackOutletIdealSplit_TwoValve_v01", ...
        'flowPath', ...
            "stack_cathode_outlet_to_ideal_split_then_V_EGR_to_compressor_inlet_and_V_BP_to_ambient_exhaust", ...
        'replacedTopology', ...
            "valve-after-split_with_post-backpressure_gas_boundary", ...
        'postBackpressureGasBoundaryPresent', false), ...
    'pressureReadback', struct( ...
        'idealNodeTolerance_kPa', .1, ...
        'requiredEqualities', ...
            "p_stack_out_approximately_p_split_approximately_p_EGR_up;_p_EGR_down_approximately_p_comp_in", ...
        'requiredDrops', ...
            "delta_p_EGR=p_EGR_up-p_EGR_down;_delta_p_BP=p_split-p_ambient"), ...
    'liquidWaterBoundary', ...
        "gas_phase_only;_no_liquid_inventory_transport_drain_or_compressor_wet-gas_tolerance_model");
end

function settings = defaultSettings(overrides)
settings = struct( ...
    'totalFlowFractions', [0 .10 .25 .50 .75 1.00], ...
    'freshAirRecirculationR', [0 .10 .50 1 2 4 8], ...
    'researchDuration_s', 600, ...
    'tailLogicalWindow_s', [540 600], ...
    'steadyWindowDuration_s', 60, ...
    'startupRampDuration_s', 60, ...
    'poolProfile', "local", ...
    'workerCount', 4, ...
    'resultDir', "", ...
    'resultTag', "20260820");
if ~isstruct(overrides) || ~isscalar(overrides)
    error('RouteA:External240kWCEGRMatrixOverrides', ...
        'overrides must be a scalar struct.');
end
names = fieldnames(overrides);
for idx = 1:numel(names)
    if ~isfield(settings, names{idx})
        error('RouteA:External240kWCEGRMatrixOverride', ...
            'Unsupported cEGR-matrix override: %s.', names{idx});
    end
    settings.(names{idx}) = overrides.(names{idx});
end
validateattributes(settings.totalFlowFractions, {'numeric'}, ...
    {'vector', 'real', 'finite', '>=', 0, '<=', 1});
validateattributes(settings.freshAirRecirculationR, {'numeric'}, ...
    {'vector', 'real', 'finite', '>=', 0, '<=', 8});
if settings.totalFlowFractions(1) ~= 0 || ...
        settings.freshAirRecirculationR(1) ~= 0
    error('RouteA:External240kWCEGRMatrixZero', ...
        'Both batches must include the R_EGR=0 reference case.');
end
validateattributes(settings.researchDuration_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(settings.tailLogicalWindow_s, {'numeric'}, ...
    {'vector', 'numel', 2, 'real', 'finite', 'nonnegative'});
if settings.tailLogicalWindow_s(1) >= settings.tailLogicalWindow_s(2) || ...
        settings.tailLogicalWindow_s(2) > settings.researchDuration_s
    error('RouteA:External240kWCEGRMatrixTailWindow', ...
        'tailLogicalWindow_s must be increasing and inside researchDuration_s.');
end
validateattributes(settings.steadyWindowDuration_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive', '<=', ...
    diff(settings.tailLogicalWindow_s)});
validateattributes(settings.startupRampDuration_s, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'nonnegative', '<', settings.researchDuration_s});
validateattributes(settings.workerCount, {'numeric'}, ...
    {'scalar', 'integer', 'positive'});
settings.totalFlowFractions = double(settings.totalFlowFractions(:).');
settings.freshAirRecirculationR = ...
    double(settings.freshAirRecirculationR(:).');
settings.poolProfile = string(settings.poolProfile);
end

function row = buildRow(caseCfg, condition, R, x, strategy, flowPolicy)
row = rowTemplate();
row.caseId = caseCfg.caseId;
row.flowStrategy = strategy;
row.flowPolicy = flowPolicy;
row.currentDensity_A_cm2 = condition.currentDensity_A_cm2;
row.referenceOER = condition.referenceOER;
row.cathodePressureGauge_kPa = condition.cathodePressureGauge_kPa;
row.cathodePressureAbsolute_MPa = caseCfg.cathode.outletPressure_MPa_abs;
row.cathodeGasTemperature_C = condition.cathodeGasTemperature_C;
row.stackTemperature_C = condition.stackTemperature_C;
row.targetRecirculationR = R;
row.controllerTargetMixFraction = x;
end

function row = rowTemplate()
row = struct( ...
    'caseId', "", 'flowStrategy', "", 'flowPolicy', "", ...
    'currentDensity_A_cm2', NaN, 'referenceOER', NaN, ...
    'cathodePressureGauge_kPa', NaN, ...
    'cathodePressureAbsolute_MPa', NaN, ...
    'cathodeGasTemperature_C', NaN, 'stackTemperature_C', NaN, ...
    'targetRecirculationR', NaN, 'controllerTargetMixFraction', NaN);
end

function text = numericLabel(value, decimals)
format = "%." + string(decimals) + "f";
text = replace(string(sprintf(char(format), value)), '.', 'p');
end
